"""
Autonomous Data & Schema Studio — Schema Memory Glossary & Documentation Exporter.
Maintains business definitions, enum mappings, and export to Markdown & dbt sources.yml.
"""

import json
from typing import Dict, Any, List, Optional
from services.app_db import StudioAppDB


class GlossaryManager:
    def __init__(self, app_db: Optional[StudioAppDB] = None):
        self.app_db = app_db or StudioAppDB()

    def propose_entry(
        self,
        connection_id: str,
        target_kind: str,
        target: str,
        kind: str,
        body: str,
        evidence: Optional[Dict[str, Any]] = None,
        author_kind: str = "agent",
    ) -> str:
        return self.app_db.record_glossary_entry(
            connection_id=connection_id,
            target_kind=target_kind,
            target=target,
            kind=kind,
            body=body,
            status="suggested",
            author_kind=author_kind,
            evidence=evidence,
        )

    def set_entry_status(self, entry_id: str, status: str):
        with self.app_db._get_connection() as conn:
            conn.execute(
                "UPDATE glossary_entries SET status = ?, updated_at = datetime('now', 'utc') WHERE id = ?;",
                (status, entry_id),
            )
            conn.commit()

    def list_entries(self, connection_id: str, status: Optional[str] = None) -> List[Dict[str, Any]]:
        with self.app_db._get_connection() as conn:
            if status:
                rows = conn.execute(
                    "SELECT * FROM glossary_entries WHERE connection_id = ? AND status = ? ORDER BY target ASC;",
                    (connection_id, status),
                ).fetchall()
            else:
                rows = conn.execute(
                    "SELECT * FROM glossary_entries WHERE connection_id = ? ORDER BY target ASC;",
                    (connection_id,),
                ).fetchall()
            return [dict(r) for r in rows]

    def export_markdown(self, connection_id: str, structure: Dict[str, Any]) -> str:
        """Generates comprehensive Markdown data dictionary with confirmed glossary terms."""
        confirmed_glossary = {
            e["target"]: e["body"]
            for e in self.list_entries(connection_id, status="confirmed")
        }

        tables = structure.get("tables", [])
        lines = [
            "# Data Dictionary & Schema Catalog",
            f"Total Tables: {len(tables)} | Generated by Dimension Autonomous Data Studio\n",
        ]

        for tbl in tables:
            t_name = tbl["name"]
            t_desc = confirmed_glossary.get(t_name, "No table description documented.")
            lines.append(f"## Table: `{t_name}`")
            lines.append(f"> {t_desc}\n")

            lines.append("| Column | Type | Nullable | Key | Meaning / Business Rules |")
            lines.append("| :--- | :--- | :--- | :--- | :--- |")

            for col in tbl.get("columns", []):
                c_name = col["name"]
                c_type = col["type"]
                nullable = "YES" if col["nullable"] else "NO"
                is_pk = "PK" if col["primary_key"] else ""

                qual_col = f"{t_name}.{c_name}"
                col_glossary = confirmed_glossary.get(qual_col, "-")
                lines.append(f"| `{c_name}` | `{c_type}` | {nullable} | {is_pk} | {col_glossary} |")

            # Document foreign keys
            fks = tbl.get("foreign_keys", [])
            if fks:
                lines.append("\n**Relationships:**")
                for fk in fks:
                    c_cols = ", ".join(fk.get("constrained_columns", []))
                    r_tbl = fk.get("referred_table", "")
                    r_cols = ", ".join(fk.get("referred_columns", []))
                    lines.append(f"- Foreign Key `{c_cols}` $\\to$ `{r_tbl}({r_cols})`")

            lines.append("\n---\n")

        return "\n".join(lines)

    def export_dbt_sources(
        self,
        connection_id: str,
        structure: Dict[str, Any],
        source_name: str = "raw_source",
    ) -> str:
        """Generates dbt sources.yml with data quality tests on PKs and confirmed FKs."""
        confirmed_glossary = {
            e["target"]: e["body"]
            for e in self.list_entries(connection_id, status="confirmed")
        }

        tables = structure.get("tables", [])
        lines = [
            "version: 2",
            "",
            "sources:",
            f"  - name: {source_name}",
            f"    description: Automated ingestion schema introspected by Dimension Studio.",
            "    tables:",
        ]

        for tbl in tables:
            t_name = tbl["name"]
            t_desc = confirmed_glossary.get(t_name, f"Source table {t_name}")
            lines.append(f"      - name: {t_name}")
            lines.append(f'        description: "{t_desc}"')
            lines.append("        columns:")

            pks = set(tbl.get("primary_keys", []))
            for col in tbl.get("columns", []):
                c_name = col["name"]
                qual_name = f"{t_name}.{c_name}"
                col_desc = confirmed_glossary.get(qual_name, f"Column {c_name}")
                lines.append(f"          - name: {c_name}")
                lines.append(f'            description: "{col_desc}"')

                # Add dbt tests for primary keys
                if c_name in pks:
                    lines.append("            tests:")
                    lines.append("              - unique")
                    lines.append("              - not_null")

            # Add relationships tests for foreign keys
            for fk in tbl.get("foreign_keys", []):
                ref_tbl = fk.get("referred_table")
                c_cols = fk.get("constrained_columns", [])
                r_cols = fk.get("referred_columns", [])
                if ref_tbl and len(c_cols) == 1 and len(r_cols) == 1:
                    lines.append(f"              - relationships:")
                    lines.append(f"                  to: source('{source_name}', '{ref_tbl}')")
                    lines.append(f"                  field: {r_cols[0]}")

            lines.append("")

        return "\n".join(lines)
